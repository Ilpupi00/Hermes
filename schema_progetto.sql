-- Hermes development schema.
--
-- This file is executed automatically by the official PostgreSQL image only
-- when the database volume is empty. Schema evolution on an existing database
-- will be managed with Alembic in a later phase.

CREATE TABLE utenti (
    id_utente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    hub_token VARCHAR(255)
);

CREATE TABLE amministratori (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    hashed_password VARCHAR(255) NOT NULL
);

CREATE TABLE modellillm (
    id_modello INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_modello VARCHAR(100) NOT NULL,
    tipo VARCHAR(20) NOT NULL DEFAULT 'hf_api',
    endpoint_url VARCHAR(500),
    descrizione TEXT,
    CONSTRAINT modellillm_tipo_check
        CHECK (tipo IN ('hf_api', 'local_url', 'hf_local'))
);

COMMENT ON COLUMN modellillm.tipo IS
    'Inference mode: hf_api, local_url or hf_local';
COMMENT ON COLUMN modellillm.endpoint_url IS
    'OpenAI-compatible endpoint used only for local_url models';

CREATE TABLE task (
    id_task INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_utente INTEGER REFERENCES utenti(id_utente),
    id_modello INTEGER REFERENCES modellillm(id_modello),
    nome VARCHAR(100) NOT NULL,
    stato VARCHAR(50) DEFAULT 'Bozza',
    prompt TEXT,
    dynamic_prompt TEXT,
    data_creazione TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    temperatura DOUBLE PRECISION DEFAULT 0.1,
    max_tokens INTEGER DEFAULT 500
);

CREATE TABLE filecsv (
    id_file INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_file VARCHAR(255) NOT NULL,
    numero_righe INTEGER NOT NULL CHECK (numero_righe >= 0)
);

CREATE TABLE mapping (
    id_mapping INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_task INTEGER REFERENCES task(id_task) ON DELETE CASCADE,
    colonna_csv VARCHAR(100) NOT NULL,
    placeholder_prompt VARCHAR(100) NOT NULL
);

CREATE TABLE righeinput (
    id_riga_input INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_file INTEGER REFERENCES filecsv(id_file) ON DELETE CASCADE,
    indice_riga INTEGER NOT NULL,
    contenuto TEXT NOT NULL
);

CREATE TABLE esecuzione (
    id_esecuzione INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_task INTEGER REFERENCES task(id_task),
    stato VARCHAR(50),
    data_inizio TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    data_fine TIMESTAMP WITHOUT TIME ZONE,
    totale_righe INTEGER NOT NULL DEFAULT 0 CHECK (totale_righe >= 0)
);

CREATE TABLE risultato (
    id_risultato INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_esecuzione INTEGER REFERENCES esecuzione(id_esecuzione),
    id_riga_input INTEGER REFERENCES righeinput(id_riga_input) ON DELETE CASCADE,
    id_file INTEGER REFERENCES filecsv(id_file) ON DELETE CASCADE,
    output TEXT,
    tempo_esecuzione DOUBLE PRECISION,
    stato VARCHAR(50)
);
